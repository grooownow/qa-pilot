import json
import tempfile
import unittest
from pathlib import Path

from profile_drift import check, main, script_ref

PROFILE = """# QA Project Profile
> Generated by qa-pilot:onboard on 2026-10-01.

## Test layers
| Layer | Path(s) | Command | Runs in CI | Phased out? |
|---|---|---|---|---|
| unit | `src/**/*.test.ts` | `pnpm test` | yes — job `ci`, on PR | no |
| e2e | `e2e/` | `pnpm test:e2e` | yes — job `e2e`, on PR | no |
| visual | `visual/` | `pnpm test:visual` | no — local only | no |

## Commands
- all tests: `pnpm test`
- typecheck: `pnpm typecheck`
- config: `playwright.config.ts`

## Conventions
- nothing here is checked
"""

SCRIPTS = {"test": "vitest run", "test:e2e": "playwright test", "test:visual": "playwright test -c visual",
           "typecheck": "tsc --noEmit"}

WORKFLOW = """name: ci
on: pull_request
jobs:
  ci:
    steps:
      - run: pnpm install
      - run: pnpm test
  e2e:
    steps:
      - name: Run playwright tests
        run: pnpm test:e2e
"""


class DriftTest(unittest.TestCase):
    def repo(self, scripts=SCRIPTS, workflow=WORKFLOW, profile=PROFILE, paths=("e2e", "visual")):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        root = Path(tmp.name)
        (root / "package.json").write_text(json.dumps({"scripts": scripts}))
        (root / "playwright.config.ts").write_text("")
        (root / "src").mkdir()
        (root / "src" / "a.test.ts").write_text("")
        for p in paths:
            (root / p).mkdir()
        if workflow is not None:
            (root / ".github" / "workflows").mkdir(parents=True)
            (root / ".github" / "workflows" / "ci.yml").write_text(workflow)
        (root / "docs" / "qa").mkdir(parents=True)
        (root / "docs" / "qa" / "project-profile.md").write_text(profile)
        return root

    def kinds(self, root):
        drifts, _ = check(root, (root / "docs/qa/project-profile.md").read_text())
        return [kind for kind, _ in drifts]

    def test_fresh_profile_has_no_drift(self):
        self.assertEqual(self.kinds(self.repo()), [])

    def test_renamed_script_is_missing(self):
        scripts = {k: v for k, v in SCRIPTS.items() if k != "typecheck"} | {"types": "tsc"}
        self.assertEqual(self.kinds(self.repo(scripts=scripts)), ["missing-script"])

    def test_moved_test_dir_is_missing_path(self):
        self.assertEqual(self.kinds(self.repo(paths=("visual",))), ["missing-path"])

    def test_layer_dropped_from_ci(self):
        workflow = WORKFLOW[:WORKFLOW.index("  e2e:")]
        self.assertEqual(self.kinds(self.repo(workflow=workflow)), ["left-ci"])

    def test_layer_added_to_ci(self):
        workflow = WORKFLOW + "      - run: pnpm test:visual\n"
        self.assertEqual(self.kinds(self.repo(workflow=workflow)), ["joined-ci"])

    def test_ci_runs_unknown_test_command(self):
        scripts = SCRIPTS | {"test:a11y": "playwright test a11y"}
        workflow = WORKFLOW + "      - run: pnpm run test:a11y\n"
        self.assertEqual(self.kinds(self.repo(scripts=scripts, workflow=workflow)), ["new-ci-command"])

    def test_ci_through_wrapper_script_counts(self):
        scripts = SCRIPTS | {"ci:all": "pnpm test && pnpm test:e2e"}
        workflow = "jobs:\n  ci:\n    steps:\n      - run: pnpm ci:all\n"
        self.assertEqual(self.kinds(self.repo(scripts=scripts, workflow=workflow)), [])

    def test_ci_inlining_the_script_body_counts(self):
        scripts = SCRIPTS | {"test:e2e": "pnpm build && playwright test --config e2e/pw.config.ts"}
        workflow = WORKFLOW.replace("run: pnpm test:e2e", "run: pnpm exec playwright test --config=e2e/pw.config.ts")
        self.assertEqual(self.kinds(self.repo(scripts=scripts, workflow=workflow)), [])

    def test_ci_job_named_in_profile_counts(self):
        workflow = WORKFLOW.replace("run: pnpm test:e2e", "run: pnpm tsx tools/run-e2e.ts")
        self.assertEqual(self.kinds(self.repo(workflow=workflow)), [])

    def test_manual_only_workflow_is_not_ci(self):
        workflow = WORKFLOW.replace("on: pull_request", "on:\n  workflow_dispatch:\n    inputs:\n      x:\n        type: boolean")
        self.assertEqual(set(self.kinds(self.repo(workflow=workflow))), {"left-ci"})
        moved = WORKFLOW[:WORKFLOW.index("  e2e:")]
        manual = "on: workflow_dispatch\njobs:\n  v:\n    steps:\n      - run: pnpm test:e2e\n"
        root = self.repo(workflow=moved)
        (root / ".github/workflows/manual.yml").write_text(manual)
        self.assertEqual(self.kinds(root), ["left-ci"])

    def test_package_binary_is_not_a_missing_script(self):
        profile = PROFILE.replace("- config:", "- list: `pnpm playwright test --list`\n- config:")
        self.assertEqual(self.kinds(self.repo(profile=profile)), [])

    def test_bare_file_name_found_anywhere(self):
        profile = PROFILE.replace("- config:", "- lanes: `lanes.ts`\n- config:")
        root = self.repo(profile=profile)
        self.assertEqual(self.kinds(root), ["missing-path"])
        (root / "e2e" / "lanes.ts").write_text("")
        self.assertEqual(self.kinds(root), [])

    def test_monorepo_reads_ci_from_repo_root(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        top = Path(tmp.name)
        (top / ".git").mkdir()
        (top / ".github" / "workflows").mkdir(parents=True)
        (top / ".github/workflows/ci.yml").write_text(WORKFLOW.replace("pnpm test:e2e", "cd web && pnpm test:e2e"))
        (top / ".github/workflows/backend.yml").write_text("on: push\njobs:\n  b:\n    steps:\n      - run: pytest\n")
        root = top / "web"
        for p in ("e2e", "visual", "src", "docs/qa"):
            (root / p).mkdir(parents=True)
        (root / "package.json").write_text(json.dumps({"scripts": SCRIPTS}))
        (root / "playwright.config.ts").write_text("")
        (root / "docs/qa/project-profile.md").write_text(PROFILE)
        # backend.yml does not mention web/, so its pytest is not a new command of this project
        self.assertEqual(self.kinds(root), [])

    def test_script_name_prefix_is_not_a_match(self):
        # The unit job is gone; `pnpm test:e2e` must not count as running `pnpm test`.
        workflow = WORKFLOW.replace("  ci:\n    steps:\n      - run: pnpm install\n      - run: pnpm test\n", "")
        self.assertEqual(self.kinds(self.repo(workflow=workflow)), ["left-ci"])
        # A longer script that merely starts with the local-only one does not put it in CI.
        scripts = SCRIPTS | {"test:visual-regression": "playwright test -c vr"}
        workflow = WORKFLOW + "      - run: pnpm test:visual-regression\n"
        self.assertEqual(self.kinds(self.repo(scripts=scripts, workflow=workflow)), ["new-ci-command"])

    def test_ci_inlining_a_named_script_through_the_package_manager(self):
        scripts = SCRIPTS | {"test:storybook": "pnpm codegen && vitest --project storybook --run"}
        profile = PROFILE.replace("- typecheck:", "- storybook: `pnpm test:storybook`\n- typecheck:")
        workflow = WORKFLOW + "      - run: pnpm vitest --project storybook --run --reporter=default 2>&1 | tee out.log\n"
        self.assertEqual(self.kinds(self.repo(scripts=scripts, profile=profile, workflow=workflow)), [])

    def test_manual_wording_means_not_in_ci(self):
        profile = PROFILE.replace("no — local only", "manual, before release")
        self.assertEqual(self.kinds(self.repo(profile=profile)), [])

    def test_monorepo_dir_name_must_match_whole(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        top = Path(tmp.name)
        (top / ".git").mkdir()
        (top / ".github" / "workflows").mkdir(parents=True)
        (top / ".github/workflows/ci.yml").write_text(WORKFLOW.replace("pnpm test:e2e", "cd web && pnpm test:e2e"))
        (top / ".github/workflows/assets.yml").write_text("on: push\njobs:\n  a:\n    steps:\n      - run: webpack && jest\n")
        root = top / "web"
        for p in ("e2e", "visual", "src", "docs/qa"):
            (root / p).mkdir(parents=True)
        (root / "package.json").write_text(json.dumps({"scripts": SCRIPTS}))
        (root / "playwright.config.ts").write_text("")
        (root / "docs/qa/project-profile.md").write_text(PROFILE)
        # assets.yml mentions "webpack", not the web/ project: its jest is not a new command here
        self.assertEqual(self.kinds(root), [])

    def test_no_ci_files_skips_ci_checks(self):
        self.assertEqual(self.kinds(self.repo(workflow=None)), [])

    def test_exit_codes(self):
        root = self.repo()
        self.assertEqual(main(["x", "--root", str(root)]), 0)
        (root / "visual").rmdir()
        self.assertEqual(main(["x", "--root", str(root)]), 1)
        self.assertEqual(main(["x", "--root", str(root), "--profile", "nope.md"]), 2)


class ScriptRefTest(unittest.TestCase):
    def test_package_managers(self):
        self.assertEqual(script_ref("npm test"), ("pm", "test"))
        self.assertEqual(script_ref("npm run test:e2e -- --headed"), ("pm", "test:e2e"))
        self.assertEqual(script_ref("pnpm --filter web test:e2e"), ("pm", "test:e2e"))
        self.assertEqual(script_ref("npm -w app run lint"), ("pm", "lint"))
        self.assertEqual(script_ref("yarn lint"), ("pm", "lint"))
        self.assertEqual(script_ref("make test"), ("make", "test"))
        self.assertEqual(script_ref("make -C web test"), ("make", "test"))
        self.assertEqual(script_ref("yarn workspace web test:e2e"), ("pm", "test:e2e"))

    def test_not_scripts(self):
        self.assertIsNone(script_ref("pnpm install"))
        self.assertIsNone(script_ref("pnpm exec playwright test"))
        self.assertIsNone(script_ref("npx playwright test"))
        self.assertIsNone(script_ref("npm ci"))


if __name__ == "__main__":
    unittest.main()
